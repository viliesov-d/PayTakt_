import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const file=path=>readFileSync(new URL(path,import.meta.url),'utf8')
const app=file('../src/App.tsx')
const main=file('../src/main.tsx')
const nativeNav=file('../src/components/MobileNavigation.tsx')
const webNav=file('../src/components/WebMobileNavigation.tsx')
const webCss=file('../src/styles/web-liquid-dock.css')
const nativeCss=file('../src/styles/navigation-slider.css')
const index=file('../index.html')
const manifest=JSON.parse(file('../public/manifest.webmanifest'))
const sw=file('../public/sw.js')

test('website uses a separate browser input handler while preserving both optical lenses',()=>{
  assert.match(app,/isNativeMobile&&<MobileNavigation/)
  assert.match(app,/platform==='web'&&<WebMobileNavigation/)
  assert.match(app,/appearanceStyle=\{appearance\.style\}/)
  assert.match(app,/glass=\{nativeOpticalGlass\}/)
  assert.match(webNav,/<OpticalGlass radius=\{27\} strength=\{24\} dock reflectiveRim\/>/)
  assert.match(webNav,/<OpticalGlass radius=\{21\} strength=\{15\} dock\/>/)
  assert.match(nativeNav,/<OpticalGlass radius=\{27\} strength=\{24\} dock reflectiveRim\/>/)
  assert.match(nativeNav,/<OpticalGlass radius=\{21\} strength=\{15\} dock\/>/)
  assert.match(webCss,/data-pressed='true'[\s\S]*?scale\(1\.075,1\.105\)/)
  assert.match(webCss,/prefers-reduced-transparency:reduce/)
  assert.match(webCss,/prefers-reduced-motion:reduce/)
  assert.match(webNav,/onClick=\{\(\)=>select\(item\.id\)\}/)
  assert.match(webNav,/setPointerCapture\(event\.pointerId\)/)
  assert.match(webNav,/setPreview\(sample\(event\.clientX\)\)/)
  assert.match(webNav,/\(target\?\?event\.currentTarget\)\.setPointerCapture\(event\.pointerId\)/)
  assert.match(webNav,/event\.target===event\.currentTarget/)
  assert.match(webNav,/\{glass&&<OpticalGlass radius=\{27\} strength=\{24\} dock reflectiveRim\/>\}/)
  assert.match(webNav,/\{glass&&<OpticalGlass radius=\{21\} strength=\{15\} dock\/>\}/)
  assert.match(webNav,/glass=appearanceStyle==='glass'/)
  assert.match(webCss,/--pt-web-thumb-offset/)
  assert.match(webCss,/translate3d\(var\(--pt-web-thumb-offset,0px\),0,0\)/)
  assert.match(webCss,/--pt-web-thumb-width/)
  assert.match(webCss,/\.pt-web-slider\.pt-optical-host > \.pt-nav-thumb,[\s\S]*?position:absolute!important;/)
  assert.match(webCss,/\[data-ui-style='classic'\][\s\S]*?background:var\(--panel\)!important;/)
  assert.match(webCss,/\[data-ui-style='soft'\][\s\S]*?background:var\(--mint-soft\)!important;/)
  assert.match(webCss,/backdrop-filter:none!important;/)
  assert.doesNotMatch(nativeNav,/pt-web-slider|suppressClickUntil/)
  assert.match(nativeCss,/html:is\(\.paytakt-native-android,\.paytakt-native-ios\)/)
})
test('mobile web styles are scoped away from native and desktop navigation',()=>{
  assert.match(webCss,/@media \(max-width:880px\)/)
  assert.match(webCss,/html:not\(:is\(\.paytakt-native-android,\.paytakt-native-ios\)\)/)
  assert.match(webCss,/\.zmina-site-header \.zmina-primary-nav/)
  assert.match(webCss,/env\(safe-area-inset-bottom,0px\)/)
  assert.match(main,/import '\.\/styles\/web-liquid-dock\.css'/)
})
test('standalone install metadata and bounded offline shell are configured',()=>{
  assert.match(index,/<link rel="manifest" href="\.\/manifest\.webmanifest"/)
  assert.match(index,/apple-touch-icon/)
  assert.equal(manifest.display,'standalone')
  assert.equal(manifest.start_url,'./')
  assert.equal(manifest.scope,'./')
  assert.ok(manifest.icons.some(icon=>icon.sizes==='192x192'&&icon.type==='image/png'))
  assert.ok(manifest.icons.some(icon=>icon.sizes==='512x512'&&icon.type==='image/png'))
  assert.match(main,/initWebPwa\(\)/)
  assert.match(sw,/request\.mode==='navigate'/)
  assert.match(sw,/baseUrl\.pathname\+'assets\/'/)
  assert.doesNotMatch(sw,/firestore\.googleapis\.com|identitytoolkit\.googleapis\.com/)
})
test('PWA installation is offered in settings without changing native update logic',()=>{
  assert.match(app,/platform==='web'\?<PwaInstallCard/)
  assert.match(app,/section==='data'&&<>\{pwaPanel\}\{syncPanel\}\{updatesPanel\}<\/>/)
  assert.match(file('../src/lib/webPwa.ts'),/nativePlatform\(\)!=='web'/)
  assert.match(file('../src/components/PwaInstallCard.tsx'),/requestWebInstall\(\)/)
})

test('browser drag stays attached to the pressed button and never resets on child capture loss',()=>{
  assert.match(webNav,/event.target instanceof Element\?event.target.closest\('button'\):null/)
  assert.match(webNav,/const target=current.dragged\?items\[Math.round\(sample\(event.clientX\)\)\]:null/)
  assert.match(webNav,/setDragging\(true\)/)
  assert.match(webCss,/transition:none!important/)
})
